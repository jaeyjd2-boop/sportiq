# rgb(a)() triples of the same colours.
def _rgb(h: str) -> Tuple[int, int, int]:
    return int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)


RGB_MAP: Dict[Tuple[int, int, int], Tuple[int, int, int]] = {_rgb(k): _rgb(v) for k, v in HEX_MAP.items()}

_HEX_RE = re.compile(r"#(?:" + "|".join(re.escape(k[1:]) for k in HEX_MAP) + r")(?![0-9a-fA-F])", re.I)
_RGB_RE = re.compile(r"\b(rgba?\(\s*)(\d{1,3})(\s*,\s*)(\d{1,3})(\s*,\s*)(\d{1,3})")


def remap(text: str) -> str:
    if not text:
        return text
    out = _HEX_RE.sub(lambda m: HEX_MAP[m.group(0).lower()], text)

    def _rgb_sub(m: "re.Match[str]") -> str:
        key = (int(m.group(2)), int(m.group(4)), int(m.group(6)))
        new = RGB_MAP.get(key)
        if not new:
            return m.group(0)
        return f"{m.group(1)}{new[0]}{m.group(3)}{new[1]}{m.group(5)}{new[2]}"

    return _RGB_RE.sub(_rgb_sub, out)


# --------------------------------------------------------------------------
# Middleware: remap colours in HTML / JS / CSS responses
# --------------------------------------------------------------------------
_TEXT_TYPES = (b"text/html", b"application/javascript", b"text/javascript", b"text/css")
_CACHE: "OrderedDict[bytes, bytes]" = OrderedDict()
_CACHE_LOCK = threading.Lock()
_CACHE_MAX = 32


def _remap_body(body: bytes) -> bytes:
    key = hashlib.blake2b(body, digest_size=16).digest()
    with _CACHE_LOCK:
        hit = _CACHE.get(key)
        if hit is not None:
            _CACHE.move_to_end(key)
            return hit
    try:
        out = remap(body.decode("utf-8")).encode("utf-8")
    except UnicodeDecodeError:
        out = body
    with _CACHE_LOCK:
        _CACHE[key] = out
        while len(_CACHE) > _CACHE_MAX:
            _CACHE.popitem(last=False)
    return out


class ThemeMiddleware:
    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope.get("type") != "http" or scope.get("method") != "GET" or os.environ.get("SPORTIQ_THEME_REMAP") == "0":
            await self.app(scope, receive, send)
            return

        start = {}
        chunks = []
        state = {"mode": None}  # None until headers seen; "pass" or "buffer"

        async def _send(message):
            if message["type"] == "http.response.start":
                headers = message.get("headers") or []
                ctype = next((v for k, v in headers if k.lower() == b"content-type"), b"").lower()
                enc = next((v for k, v in headers if k.lower() == b"content-encoding"), b"")
                if any(ctype.startswith(t) for t in _TEXT_TYPES) and not enc:
                    state["mode"] = "buffer"
                    start.update(message)
                    return
                state["mode"] = "pass"
                await send(message)
                return
            if message["type"] == "http.response.body" and state["mode"] == "buffer":
                chunks.append(message.get("body", b""))
                if message.get("more_body"):
                    return
                body = _remap_body(b"".join(chunks))
                headers = [(k, v) for k, v in (start.get("headers") or []) if k.lower() != b"content-length"]
                headers.append((b"content-length", str(len(body)).encode("latin-1")))
                await send(dict(start, headers=headers))
                await send({"type": "http.response.body", "body": body, "more_body": False})
                return
            await send(message)

        await self.app(scope, receive, _send)


