_BYTES: Dict[str, bytes] = {}


def brand_bytes(name: str) -> bytes:
    if name not in _BYTES:
        with open(os.path.join(BRAND_DIR, name), "rb") as f:
            _BYTES[name] = f.read()
    return _BYTES[name]


def _make_route(path: str, fname: str, ctype: str):
    def _serve():
        return Response(content=brand_bytes(fname), media_type=ctype, headers={"Cache-Control": "public, max-age=86400"})

    _serve.__name__ = "brand_" + re.sub(r"\W", "_", fname)
    router.add_api_route(path, _serve, methods=["GET", "HEAD"])


for _p, (_f, _t) in _FILES.items():
    _make_route(_p, _f, _t)

